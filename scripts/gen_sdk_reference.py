"""Keep learnings/anthropic-sdk-reference.md honest.

    .venv/bin/python scripts/gen_sdk_reference.py          # rewrite the generated appendix
    .venv/bin/python scripts/gen_sdk_reference.py --check  # only verify the claims made in the text

The appendix (everything between the BEGIN/END GENERATED markers in the markdown file) is built
by reading the installed SDK's own type definitions, so it can't drift from the SDK. The text
above the appendix is hand-written; --check asserts the specific claims that text makes, so an
SDK upgrade that breaks one of them is caught.
"""
import inspect
import pathlib
import re
import sys
import typing

import anthropic
from anthropic import types as T
from anthropic.types.cache_creation import CacheCreation
from anthropic.types.output_tokens_details import OutputTokensDetails

DOC = pathlib.Path(__file__).resolve().parent.parent / "learnings" / "anthropic-sdk-reference.md"
BEGIN, END = "<!-- BEGIN GENERATED -->", "<!-- END GENERATED -->"


def pretty(annotation) -> str:
    """A short, readable version of a type annotation."""
    s = str(annotation)
    s = s.replace("typing.", "").replace("<class '", "").replace("'>", "")
    s = re.sub(r"anthropic\.types\.[a-z0-9_\.]+\.", "", s)
    s = re.sub(r"Annotated\[(.*?),\s*PropertyInfo\([^)]*\)\]", r"\1", s)
    return (s[:78] + "...") if len(s) > 80 else s


def model_table(cls) -> str:
    rows = ["| field | required? | type |", "|---|---|---|"]
    for name, f in cls.model_fields.items():
        rows.append(f"| `{name}` | {'yes' if f.is_required() else 'no'} | `{pretty(f.annotation)}` |")
    return "\n".join(rows)


def typed_dict_table(cls) -> str:
    hints = typing.get_type_hints(cls, include_extras=True)
    rows = ["| key | required? | type |", "|---|---|---|"]
    for name, h in hints.items():
        req = "Required" in str(h) and "NotRequired" not in str(h)
        rows.append(f"| `{name}` | {'yes' if req else 'no'} | `{pretty(h)}` |")
    return "\n".join(rows)


def build_appendix() -> str:
    out = [f"SDK version: `anthropic` {anthropic.__version__}. Generated by `scripts/gen_sdk_reference.py`; do not edit by hand.", ""]
    out.append("### Request side (plain dicts)\n")
    for cls in (T.MessageParam, T.ToolParam, T.ToolResultBlockParam, T.TextBlockParam, T.ToolUseBlockParam, T.ThinkingBlockParam):
        out.append(f"#### `{cls.__name__}`\n")
        out.append(typed_dict_table(cls) + "\n")
    sig = inspect.signature(anthropic.resources.messages.Messages.create)
    out.append("#### `client.messages.create(...)` parameters\n")
    rows = ["| parameter | required? |", "|---|---|"]
    for n, p in sig.parameters.items():
        if n == "self":
            continue
        required = p.default is inspect.Parameter.empty and p.kind != p.VAR_KEYWORD
        rows.append(f"| `{n}` | {'yes' if required else 'no'} |")
    out.append("\n".join(rows) + "\n")
    out.append("### Response side (objects; read with a dot)\n")
    for cls in (T.Message, T.Usage, OutputTokensDetails, CacheCreation, T.TextBlock, T.ThinkingBlock, T.ToolUseBlock):
        out.append(f"#### `{cls.__name__}`\n")
        out.append(model_table(cls) + "\n")
    members = [t.__name__ for t in typing.get_args(typing.get_args(T.ContentBlock)[0])]
    out.append("#### Every kind of block that can appear in `Message.content`\n")
    out.append(", ".join(f"`{m}`" for m in members) + "\n")
    out.append("#### `stop_reason` values\n")
    out.append(", ".join(f"`{v}`" for v in typing.get_args(T.StopReason)) + "\n")
    return "\n".join(out)


def check_claims() -> None:
    """Assert every specific claim the hand-written text makes. Fails loudly if the SDK changed."""
    block_classes = [t for t in typing.get_args(typing.get_args(T.ContentBlock)[0])]
    assert all("usage" not in b.model_fields for b in block_classes), "a content block has its own usage"
    assert "usage" in T.Message.model_fields and "content" in T.Message.model_fields
    assert {"input_tokens", "output_tokens", "output_tokens_details"} <= set(T.Usage.model_fields)
    assert "thinking_tokens" in OutputTokensDetails.model_fields
    assert {"cache_creation_input_tokens", "cache_read_input_tokens"} <= set(T.Usage.model_fields)
    assert {"text", "type"} <= set(T.TextBlock.model_fields)
    assert {"thinking", "signature", "type"} <= set(T.ThinkingBlock.model_fields)
    assert {"id", "name", "input", "type"} <= set(T.ToolUseBlock.model_fields)
    assert {"end_turn", "max_tokens", "tool_use", "refusal"} <= set(typing.get_args(T.StopReason))
    sig = inspect.signature(anthropic.resources.messages.Messages.create)
    required = {n for n, p in sig.parameters.items() if p.default is inspect.Parameter.empty and n != "self" and p.kind != p.VAR_KEYWORD}
    assert required == {"model", "max_tokens", "messages"}, required
    assert not {"temperature", "top_p", "top_k"} & set(sig.parameters), "create() now takes sampling parameters"
    assert {"tools", "system", "tool_choice", "thinking"} <= set(sig.parameters)
    req = lambda c: {k for k, v in typing.get_type_hints(c, include_extras=True).items() if "Required" in str(v) and "NotRequired" not in str(v)}
    assert req(T.ToolParam) == {"name", "input_schema"}
    assert req(T.ToolResultBlockParam) == {"tool_use_id", "type"}
    assert req(T.MessageParam) == {"role", "content"}
    print("all claims in the text still hold for anthropic", anthropic.__version__)


def main() -> None:
    check_claims()
    if "--check" in sys.argv:
        return
    text = DOC.read_text()
    assert BEGIN in text and END in text, "markers missing in the markdown file"
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    DOC.write_text(head + BEGIN + "\n" + build_appendix() + "\n" + END + tail)
    print("rewrote the generated appendix in", DOC.relative_to(DOC.parent.parent))


if __name__ == "__main__":
    main()
